import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Use Vite's existing, locked PostCSS runtime; no extra project dependency.
const require = createRequire(import.meta.url);
const postcss = createRequire(require.resolve('vite/package.json'))('postcss');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sources = ['umaomao.css', 'umaomao-themes-v47.css', 'umaomao-reference-v47.css'];
const target = resolve(root, 'src/styles/umaomao-palette-v47.css');
const scope = ':root[data-ui-layout="v47"][data-ui-palette]:not([data-ui-palette="web3-meme"])';
const output = postcss.root();
const colorProperties = /^(color|color-scheme|-webkit-text-fill-color|background(?:-color|-image)?|(?:border(?:-(?:top|right|bottom|left|inline|block|inline-start|inline-end|block-start|block-end))?|outline|text-decoration|column-rule)-color|caret-color|accent-color|fill|stroke|stop-color|flood-color)$/;
const layoutVariable = /(font|radius|ease|duration|motion|size|width|height|spacing|shadow)/;

function paletteSelector(selector) {
  const converted = selector.replaceAll('data-ui-theme', 'data-ui-palette');
  const affirmative = converted.replace(/:not\(\[data-ui-palette=["']web3-meme["']\]\)/g, '');
  if (/\[data-ui-palette=["']web3-meme["']\]/.test(affirmative)) return null;
  if (converted.startsWith(':root')) return scope + converted;
  if (/^html\b/.test(converted)) return converted.replace(/^html/, `html${scope}`);
  return `${scope} ${converted}`;
}

function paletteDeclaration(declaration) {
  const { prop, value } = declaration;
  if (prop.startsWith('--')) return layoutVariable.test(prop) ? [] : [declaration.clone()];
  if (colorProperties.test(prop)) {
    // Artwork stays the default layout's artwork; palette changes never load a different hero photo.
    return /url\(/i.test(value) ? [] : [declaration.clone()];
  }
  if (/^(border(?:-(?:top|right|bottom|left|inline|block|inline-start|inline-end|block-start|block-end))?|outline|column-rule)$/.test(prop)) {
    const color = value.match(/\b(?:solid|dashed|dotted|double|groove|ridge|inset|outset)\s+(.+)$/)?.[1];
    return color ? [declaration.clone({ prop: `${prop}-color`, value: color })] : [];
  }
  return [];
}

function copyColors(input, destination) {
  for (const node of input.nodes ?? []) {
    if (node.type === 'atrule') {
      if (!['media', 'supports', 'container'].includes(node.name)) continue;
      const wrapper = node.clone({ nodes: [] });
      copyColors(node, wrapper);
      if (wrapper.nodes.length) destination.append(wrapper);
    } else if (node.type === 'rule') {
      const selectors = node.selectors.map(paletteSelector).filter(Boolean);
      const declarations = node.nodes.filter(child => child.type === 'decl').flatMap(paletteDeclaration);
      if (selectors.length && declarations.length) {
        destination.append(postcss.rule({ selector: selectors.join(',\n'), nodes: declarations }));
      }
    }
  }
}

for (const source of sources) {
  copyColors(postcss.parse(readFileSync(resolve(root, 'src/styles', source), 'utf8').replaceAll('\r\n', '\n')), output);
}
const header = '/* Generated by scripts/generate-v47-palette-css.mjs.\n'
  + ' * Color declarations only. The legacy data-ui-theme stays web3-meme for layout;\n'
  + ' * data-ui-palette selects colors. Frozen reference files are unchanged.\n */\n';
const generated = header + output.toString().trim() + '\n';
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== generated) throw new Error('Palette CSS is stale; regenerate it.');
  console.log('v47 palette CSS matches its frozen sources; geometry declarations are excluded.');
} else {
  writeFileSync(target, generated);
  console.log(`Generated color-only palette CSS (${output.nodes.length} rules/groups).`);
}
